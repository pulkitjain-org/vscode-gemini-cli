import { describe, expect, it } from 'vitest';
import { markedRegion, markedRegionText, refusesInstrumentation, templateLanguageOf } from '../../../src/acp/debug/templates';

const endpoint = { host: '127.0.0.1', port: 4321, token: 'abc123' };

describe('marked-line templates', () => {
	it('writes the JavaScript console region as the design shows it', () => {
		expect(markedRegion({ language: 'javascript', channel: 'console', nonce: 'gc7f3a', point: 'p4', expressions: ['cart.total'] })).toEqual([
			'// GEMINI-DEBUG-START gc7f3a p4',
			'try { console.log("@@gc:gc7f3a:p4@@", JSON.stringify({ "cart.total": (() => { try { return cart.total; } catch (e) { return "<" + e + ">"; } })() }, (k, v) => typeof v === "bigint" ? String(v) : v).slice(0, 4000)); } catch {}',
			'// GEMINI-DEBUG-END gc7f3a p4',
		]);
	});

	it('runs the JavaScript statement: each expression in its own try, BigInt as a string, never throwing', () => {
		const lines = markedRegion({ language: 'javascript', channel: 'console', nonce: 'gc7f3a', point: 'p1', expressions: ['cart.total', 'missing.deep', 'big'] });
		const printed: unknown[][] = [];
		const run = new Function('console', 'cart', 'big', lines.join('\n'));
		run({ log: (...args: unknown[]) => printed.push(args) }, { total: 9 }, 10n);
		expect(printed).toEqual([['@@gc:gc7f3a:p1@@', '{"cart.total":9,"missing.deep":"<ReferenceError: missing is not defined>","big":"10"}']]);
	});

	it('adds @ts-ignore for TypeScript, posts for the http channel, and indents every line', () => {
		expect(markedRegionText({ language: 'typescript', channel: 'http', nonce: 'gc7f3a', point: 'p2', expressions: ['total'], indent: '\t\t', endpoint })).toBe([
			'\t\t// GEMINI-DEBUG-START gc7f3a p2',
			'\t\t// @ts-ignore',
			'\t\ttry { fetch("http://127.0.0.1:4321/debug/abc123", { method: "POST", body: "@@gc:gc7f3a:p2@@ " + JSON.stringify({ "total": (() => { try { return total; } catch (e) { return "<" + e + ">"; } })() }, (k, v) => typeof v === "bigint" ? String(v) : v).slice(0, 4000), keepalive: true }).catch(() => {}); } catch {}',
			'\t\t// GEMINI-DEBUG-END gc7f3a p2',
			'',
		].join('\n'));
	});

	it('writes the Python regions: stderr flushed on console, a daemon thread with a short timeout on http', () => {
		expect({
			console: markedRegion({ language: 'python', channel: 'console', nonce: 'gc7f3a', point: 'p4', expressions: ['order.total'], indent: '    ' }),
			http: markedRegion({ language: 'python', channel: 'http', nonce: 'gc7f3a', point: 'p5', expressions: ['n'], endpoint }),
		}).toEqual({
			console: [
				'    # GEMINI-DEBUG-START gc7f3a p4',
				'    try: __import__("sys").stderr.write("@@gc:gc7f3a:p4@@ " + __import__("json").dumps({"order.total": order.total}, default=str)[:4000] + "\\n"); __import__("sys").stderr.flush()',
				'    except Exception: pass',
				'    # GEMINI-DEBUG-END gc7f3a p4',
			],
			http: [
				'# GEMINI-DEBUG-START gc7f3a p5',
				'try: (lambda b: __import__("threading").Thread(target=lambda: __import__("urllib.request").request.urlopen(__import__("urllib.request").request.Request("http://127.0.0.1:4321/debug/abc123", data=b, method="POST"), timeout=0.2), daemon=True).start())(("@@gc:gc7f3a:p5@@ " + __import__("json").dumps({"n": n}, default=str)[:4000]).encode())',
				'except Exception: pass',
				'# GEMINI-DEBUG-END gc7f3a p5',
			],
		});
	});

	it('knows the files it has a template for, and the ones it must never touch', () => {
		expect({
			languages: ['a.js', 'b.tsx', 'c.py', 'd.vue', 'e.svelte', 'f.go', 'g.json'].map(f => templateLanguageOf(f)),
			vueTs: templateLanguageOf('d.vue', 'ts'),
			refused: [
				refusesInstrumentation('package-lock.json', '{}'),
				refusesInstrumentation('app.min.js', 'x'),
				refusesInstrumentation('gen.ts', '// @generated by protoc\n'),
				refusesInstrumentation('bundle.js', `!function(){${'a'.repeat(1200)}}();`),
				refusesInstrumentation('cart.ts', 'export const x = 1;\n'),
			],
			http: (() => {
				try {
					markedRegion({ language: 'javascript', channel: 'http', nonce: 'gc7f3a', point: 'p1', expressions: ['x'] });
					return 'built';
				} catch (err) {
					return (err as Error).message;
				}
			})(),
		}).toEqual({
			languages: ['javascript', 'typescript', 'python', 'javascript', 'javascript', undefined, undefined],
			vueTs: 'typescript',
			refused: ['the file has no room for a comment, or is a lockfile', 'the file has no room for a comment, or is a lockfile', 'the file is generated', 'the file looks minified', undefined],
			http: 'The http channel needs the endpoint.',
		});
	});
});
